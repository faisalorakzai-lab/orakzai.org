  static String text(
    AppLanguage language,
    String key, [
    Map<String, String>? args,
  ]) {
    var value =
        _strings[language]?[key] ?? _strings[AppLanguage.english]![key] ?? key;
    args?.forEach((name, replacement) {
      value = value.replaceAll('{$name}', replacement);
    });
    return value;
  }

